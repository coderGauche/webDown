export const UI_MESSAGES = { en: EN_MESSAGES, 'zh-CN': ZH_MESSAGES } as const;

export function resolveUiLocale(value: unknown): UiLocale {
  return typeof value === 'string' && value.toLowerCase().startsWith('zh') ? 'zh-CN' : 'en';
}

export function translate(
  locale: UiLocale,
  key: UiMessageKey,
  values: Record<string, string | number> = {},
): string {
  return UI_MESSAGES[locale][key].replace(/\{([a-z]+)\}/gi, (_match, name: string) =>
    String(values[name] ?? `{${name}}`),
  );
}

export function localizeCaptureError(error: CaptureError, locale: UiLocale): CaptureError {
  const [message, suggestion] =
    locale === 'zh-CN'
      ? [CAPTURE_ERROR_CATALOG[error.code].message, CAPTURE_ERROR_CATALOG[error.code].suggestion]
      : ERROR_EN[error.code];
  return { ...error, message, suggestion };
}

export function hasCompleteErrorTranslations(): boolean {
  return CAPTURE_ERROR_CODES.every((code) => ERROR_EN[code]?.length === 2);
}
